/**
 * Slack Integration for Aegis
 *
 * Sends findings and scan results to Slack channels via webhooks.
 * Supports rich formatting with blocks, actions, and threading.
 */

export interface SlackConfig {
  /** Slack webhook URL */
  webhookUrl: string;
  /** Default channel to post to */
  defaultChannel?: string;
  /** Bot name */
  username?: string;
  /** Bot icon */
  iconEmoji?: string;
  /** Enable threading for replies */
  enableThreading?: boolean;
}

export interface SlackMessage {
  text: string;
  blocks?: SlackBlock[];
  thread_ts?: string;
}

export interface SlackBlock {
  type: 'section' | 'divider' | 'actions' | 'context' | 'header';
  text?: { type: 'mrkdwn' | 'plain_text'; text: string };
  elements?: Array<{ type: string; text?: string; action_id?: string; value?: string; url?: string }>;
  accessory?: { type: string; image_url?: string; alt_text?: string };
}

export interface SlackFinding {
  id: string;
  title: string;
  severity: string;
  file: string;
  line: number;
  ruleId: string;
  description: string;
  remediation?: string;
}

export interface SlackScanResult {
  target: string;
  score: number;
  grade: string;
  findings: SlackFinding[];
  criticalCount: number;
  highCount: number;
  mediumCount: number;
  lowCount: number;
}

export class SlackNotifier {
  private readonly config: SlackConfig;

  constructor(config: SlackConfig) {
    this.config = config;
  }

  /**
   * Send a message to Slack.
   */
  async sendMessage(message: SlackMessage): Promise<{ ok: boolean; ts?: string }> {
    try {
      const response = await fetch(this.config.webhookUrl, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          text: message.text,
          blocks: message.blocks,
          ...(message.thread_ts ? { thread_ts: message.thread_ts } : {}),
          ...(this.config.username ? { username: this.config.username } : {}),
          ...(this.config.iconEmoji ? { icon_emoji: this.config.iconEmoji } : {}),
        }),
      });

      if (!response.ok) {
        throw new Error(`Slack API error: ${response.status} ${response.statusText}`);
      }

      const result = await response.json() as { ok?: boolean; ts?: string };
      return { ok: result.ok ?? true, ts: result.ts };
    } catch (error) {
      console.error(`[Slack] Failed to send message: ${(error as Error).message}`);
      return { ok: false };
    }
  }

  /**
   * Send a scan completion notification.
   */
  async notifyScanComplete(result: SlackScanResult): Promise<{ ok: boolean; ts?: string }> {
    const blocks: SlackBlock[] = [
      {
        type: 'header',
        text: { type: 'plain_text', text: `🛡️ Aegis Scan Complete: ${result.target}` },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Score:* ${result.score}/100 (${result.grade})\n*Findings:* ${result.findings.length} total (${result.criticalCount} critical, ${result.highCount} high, ${result.mediumCount} medium, ${result.lowCount} low)`,
        },
      },
    ];

    // Add top critical/high findings
    const topFindings = result.findings
      .filter((f) => f.severity === 'critical' || f.severity === 'high')
      .slice(0, 5);

    if (topFindings.length > 0) {
      blocks.push({
        type: 'divider',
      });
      blocks.push({
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: '*Top Findings:*',
        },
      });

      for (const finding of topFindings) {
        blocks.push({
          type: 'section',
          text: {
            type: 'mrkdwn',
            text: `*${finding.severity.toUpperCase()}* ${finding.title}\n\`${finding.file}:${finding.line}\` (${finding.ruleId})`,
          },
        });
      }
    }

    blocks.push({
      type: 'context',
      elements: [{ type: 'mrkdwn', text: `Generated by Aegis • ${new Date().toISOString()}` }],
    });

    return this.sendMessage({
      text: `Aegis scan of ${result.target}: ${result.score}/100 (${result.grade}), ${result.findings.length} findings`,
      blocks,
    });
  }

  /**
   * Send a critical finding alert.
   */
  async notifyCriticalFinding(finding: SlackFinding): Promise<{ ok: boolean; ts?: string }> {
    const blocks: SlackBlock[] = [
      {
        type: 'header',
        text: { type: 'plain_text', text: `🚨 Critical Finding: ${finding.title}` },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Severity:* ${finding.severity}\n*File:* \`${finding.file}:${finding.line}\`\n*Rule:* \`${finding.ruleId}\``,
        },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Description:* ${finding.description}`,
        },
      },
      ...(finding.remediation
        ? [
            {
              type: 'section' as const,
              text: {
                type: 'mrkdwn' as const,
                text: `*Remediation:* ${finding.remediation}`,
              },
            },
          ]
        : []),
      {
        type: 'context',
        elements: [{ type: 'mrkdwn', text: `Finding ID: ${finding.id}` }],
      },
    ];

    return this.sendMessage({
      text: `🚨 Critical: ${finding.title} in ${finding.file}:${finding.line}`,
      blocks,
    });
  }

  /**
   * Send a red team bypass alert.
   */
  async notifyRedTeamBypass(
    attackId: string,
    attackName: string,
    severity: string,
    prompt: string,
    response: string
  ): Promise<{ ok: boolean; ts?: string }> {
    const blocks: SlackBlock[] = [
      {
        type: 'header',
        text: { type: 'plain_text', text: `🔴 Red Team Bypass: ${attackName}` },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Severity:* ${severity}\n*Attack ID:* \`${attackId}\``,
        },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Prompt:* \`\`\`${prompt.slice(0, 500)}\`\`\`\n*Response:* \`\`\`${response.slice(0, 500)}\`\`\``,
        },
      },
      {
        type: 'context',
        elements: [{ type: 'mrkdwn', text: `Generated by Aegis Red Team • ${new Date().toISOString()}` }],
      },
    ];

    return this.sendMessage({
      text: `🔴 Red Team Bypass: ${attackName} (${severity})`,
      blocks,
    });
  }

  /**
   * Send a compliance violation alert.
   */
  async notifyComplianceViolation(
    framework: string,
    control: string,
    findingCount: number,
    worstSeverity: string
  ): Promise<{ ok: boolean; ts?: string }> {
    const blocks: SlackBlock[] = [
      {
        type: 'header',
        text: { type: 'plain_text', text: `⚠️ Compliance Violation: ${framework}/${control}` },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Framework:* ${framework}\n*Control:* ${control}\n*Findings:* ${findingCount}\n*Worst Severity:* ${worstSeverity}`,
        },
      },
      {
        type: 'context',
        elements: [{ type: 'mrkdwn', text: `Generated by Aegis Compliance • ${new Date().toISOString()}` }],
      },
    ];

    return this.sendMessage({
      text: `⚠️ Compliance Violation: ${framework}/${control} (${findingCount} findings, worst: ${worstSeverity})`,
      blocks,
    });
  }
}

